import sympy as sp
import numpy as np

# 1. Define a recursive translator from LISP lists to SymPy objects
def lisp_to_sympy(expr, symbol_map):
    if not isinstance(expr, list):
        # If it's a string symbol, map it to a SymPy Symbol; if a number, return it
        return symbol_map[expr] if expr in symbol_map else expr
    
    op = expr[0]
    args = [lisp_to_sympy(arg, symbol_map) for arg in expr[1:]]
    
    # Map LISP operators directly to SymPy structural tree nodes
    mapping = {
        '+': sp.Add,
        '*': sp.Mul,
        'pow': sp.Pow,
        'sin': sp.sin,
        '=': sp.Eq
    }
    return mapping[op](*args)

# 2. Setup your symbols
x = sp.Symbol('x')
sym_map = {'x': x}

# 3. Simulate an S-expression generated by your logic system: x^2 - 4 = 0
lisp_equation = ['=', ['+', ['pow', 'x', 2], -4], 0]

# 4. Instantly build the SymPy structural tree
sympy_eq = lisp_to_sympy(lisp_equation, sym_map)
print("SymPy Tree:", repr(sympy_eq)) 
# Output: Eq(x**2 - 4, 0)

# 5. EXECUTE: Solve it symbolically
solution = sp.solve(sympy_eq, x)
print("Symbolic Solution:", solution) # Output: [-2, 2]

# 6. COMPILE: Turn it into executable fast code if needed
executable = sp.lambdify(x, sympy_eq.lhs, 'numpy')