import os
import sys
import re

class TreeNode:
    def __init__(self, feature=None, value=None, is_leaf=False, classification=None):
        self.feature = feature          
        self.value = value              
        self.is_leaf = is_leaf
        self.classification = classification  
        self.tb = None                  
        self.fb = None                  

class UnifiedNeuroSymbolicParserPipeline:
    def __init__(self, retention_depth=5):
        self.retention_depth = retention_depth
        self.level1_root = TreeNode(is_leaf=True, classification="noun")
        self.level3_root = TreeNode(is_leaf=True, classification="atom")

    def evaluate_tree(self, node, feature_vector):
        if node.is_leaf:
            return node.classification
        feat_val = feature_vector.get(node.feature)
        if feat_val == node.value:
            return self.evaluate_tree(node.tb, feature_vector)
        return self.evaluate_tree(node.fb, feature_vector)

    def train_node(self, node, feature_vector, target_class, split_feat, split_val):
        if node.is_leaf:
            if node.classification != target_class:
                node.is_leaf = False
                node.feature = split_feat
                node.value = split_val
                node.tb = TreeNode(is_leaf=True, classification=target_class)
                node.fb = TreeNode(is_leaf=True, classification=node.classification)
            return
        feat_val = feature_vector.get(node.feature)
        if feat_val == node.value:
            self.train_node(node.tb, feature_vector, target_class, split_feat, split_val)
        else:
            self.train_node(node.fb, feature_vector, target_class, split_feat, split_val)

    def compile_story_to_prolog(self, raw_sentence, strategy):
        # Clean trailing punctuation string artifacts
        cleaned_sentence = re.sub(r"[^\w\s]", "", raw_sentence)
        words = cleaned_sentence.split()
        resolved_subject = "variable"
        resolved_context = "context"
        action_token = "action"
        
        for word in words:
            l1_features = {
                "capitalized": word[0].isupper() if word else False,
                "suffix": word[-2:] if len(word) >= 2 else "none"
            }
            inferred_pos = self.evaluate_tree(self.level1_root, l1_features)
            
            l3_features = {"pos_tag": inferred_pos}
            if inferred_pos in ["proper_noun", "noun"]:
                l3_features["word_role"] = "subject"
            elif inferred_pos in ["catalyst_noun", "crisis_modifier"]:
                l3_features["word_role"] = "modifier"
            elif "verb" in inferred_pos:
                l3_features["word_role"] = "action"

            prolog_primitive_type = self.evaluate_tree(self.level3_root, l3_features)
            clean_token = word.lower() if prolog_primitive_type == "atom" else word.capitalize()
            
            if inferred_pos == "proper_noun":
                resolved_subject = clean_token
            elif inferred_pos == "crisis_modifier":
                action_token = clean_token
            elif inferred_pos == "catalyst_noun":
                resolved_context = clean_token
            elif "verb" in inferred_pos and action_token == "action":
                action_token = clean_token

        compiled_facts = []
        if strategy == "Syntactic Literal":
            compiled_facts.append(f"{action_token}({resolved_subject}).")
        elif strategy == "Functional Role":
            compiled_facts.append(f"uncontrolled_descent({resolved_subject}).")
        elif strategy == "Environmental Impact":
            compiled_facts.append(f"accident({resolved_subject}, {resolved_context}).")
                
        return compiled_facts

def write_to_filesystem_situation(strategy_name, facts_list):
    base_path = "/home/rsherman/projects/SMT-ILP/ZeroVRAM/Popper-main/examples"
    folder_mapping = {
        "Syntactic Literal": "generated_literal_space",
        "Functional Role": "generated_functional_space",
        "Environmental Impact": "generated_impact_space"
    }
    target_dir = os.path.join(base_path, folder_mapping[strategy_name])
    os.makedirs(target_dir, exist_ok=True)
    
    bk_path = os.path.join(target_dir, "bk.pl")
    with open(bk_path, "w", encoding="utf-8") as f:
        f.write(f"%% 🌴 Autogenerated Abstraction via FULL-STACK INTEGRATED PIPELINE\n")
        f.write(":- discontiguous infon/3.\n\n")
        for fact in facts_list:
            f.write(f"{fact}\n")
    return bk_path

def main():
    pipeline = UnifiedNeuroSymbolicParserPipeline()

    # 📋 STEP 1: TRAIN LEVEL 1 CORUS WITH CRITICAL MEDICAL TOKENS
    arn_vocab_training = [
        ("Judith", {"capitalized": True, "suffix": "th"}, "proper_noun", "capitalized", True),
        ("falls", {"capitalized": False, "suffix": "ls"}, "intransitive_verb", "suffix", "ls"),
        ("mountain", {"capitalized": False, "suffix": "in"}, "catalyst_noun", "suffix", "in"),
        ("is", {"capitalized": False, "suffix": "is"}, "auxiliary_verb", "suffix", "is"),
        ("bleeding", {"capitalized": False, "suffix": "ng"}, "crisis_modifier", "suffix", "ng")
    ]
    for word, features, target_pos, s_feat, s_val in arn_vocab_training:
        pipeline.train_node(pipeline.level1_root, features, target_pos, s_feat, s_val)

    # 📋 STEP 2: TRAIN LEVEL 3 SCHEMA PARSER TREE
    pos_to_prolog_training = [
        ({"pos_tag": "proper_noun", "word_role": "subject"}, "atom", "pos_tag", "proper_noun"),
        ({"pos_tag": "intransitive_verb", "word_role": "action"}, "unary_predicate", "pos_tag", "intransitive_verb"),
        ({"pos_tag": "auxiliary_verb", "word_role": "action"}, "unary_predicate", "pos_tag", "auxiliary_verb"),
        ({"pos_tag": "crisis_modifier", "word_role": "modifier"}, "atom", "pos_tag", "crisis_modifier"),
        ({"pos_tag": "catalyst_noun", "word_role": "modifier"}, "atom", "pos_tag", "catalyst_noun")
    ]
    for features, prolog_type, s_feat, s_val in pos_to_prolog_training:
        pipeline.train_node(pipeline.level3_root, features, prolog_type, s_feat, s_val)

    print("=" * 85)
    print("🌲 INTERACTIVE FULLY INTEGRATED LEVEL 1 ──> LEVEL 3 PARSER PIPELINE")
    print("=" * 85)
    print("📋 Status: Waiting for live user written text input...")
    print("-" * 85)

    try:
        user_input = input("📥 Enter text sentence to parse (e.g., Judith is bleeding): ").strip()
        if not user_input:
            user_input = "Judith is bleeding"
    except (KeyboardInterrupt, EOFError):
        user_input = "Judith is bleeding"

    print(f"\n🚀 Processing Text Token Stream: '{user_input}'\n")
    strategies = ["Syntactic Literal", "Functional Role", "Environmental Impact"]

    for strategy in strategies:
        print(f"🌀 Generating Alternative Abstraction Stream -> **{strategy}**")
        facts = pipeline.compile_story_to_prolog(user_input, strategy)
        saved_path = write_to_filesystem_situation(strategy, facts)
        facts_str = ", ".join(facts)
        print(f"   ✨ Result: {facts_str:<35} | Live Deployed -> {os.path.basename(saved_path)}")

    print("\n" + "=" * 85)
    print("📊 DUMPING AND VERIFYING DISK MATERIALIZATION TRANSFERS")
    print("=" * 85)
    print("   📁 Confirming 'generated_functional_space/bk.pl' content:")
    with open("/home/rsherman/projects/SMT-ILP/ZeroVRAM/Popper-main/examples/generated_functional_space/bk.pl", "r") as f:
        for line in f:
            if line.strip(): print(f"      {line.strip()}")
    print("=" * 85 + "\n")

if __name__ == "__main__":
    main()
