import os
import json
import pickle

class WorldLevelNode:
    def __init__(self, is_leaf=False, split_feature=None, split_value=None, classification=None):
        self.split_feature = split_feature    
        self.split_value = split_value        
        self.is_leaf = is_leaf
        self.classification = classification  
        self.tb = None                        
        self.fb = None                        

class SovereignInferencePipeline:
    def __init__(self):
        self.model_dir = "/home/rsherman/projects/SMT-ILP/ZeroVRAM/story_intake_directory/pickled_models"
        self.root_dir = "/home/rsherman/projects/SMT-ILP/ZeroVRAM/Popper-main/examples"
        self.json_path = "/home/rsherman/projects/SMT-ILP/ZeroVRAM/Counterfactual-StoryRW-master/data/life_goals_matrix.json"
        
        # Load the Sovereign tree strictly in READ-ONLY mode
        with open(os.path.join(self.model_dir, "level6_lifecycle.pkl"), "rb") as f:
            self.t6 = pickle.load(f)

    def evaluate_tree(self, node, feature_vector):
        if node is None: return "unknown"
        if node.is_leaf: return node.classification
        val = feature_vector.get(node.split_feature, "False")
        if str(val) == str(node.split_value): return self.evaluate_tree(node.tb, feature_vector)
        return self.evaluate_tree(node.fb, feature_vector)

    def run_sovereign_inference(self):
        print("=" * 95)
        print("🔮 ISOLATED SOVEREIGN INFERENCE ENGINE: INTERROGATING TOP-LEVEL LIFE LATTICES")
        print("=" * 95)
        
        with open(self.json_path, "r", encoding="utf-8") as f:
            profiles = json.load(f)

        t6_facts = []

        for p in profiles:
            subj = p["subject"]
            
            if subj == "john":
                # Execute read-only evaluation over John's active biographical features
                f_vector = {"has_supernatural_awakening": "False", "has_resolved_acceptance": "False"}
                inferred_lifecycle = self.evaluate_tree(self.t6, f_vector)
                
                print(f"📥 Interrogating Life-Track: [john]")
                print(f"   ➔ Assigned Lifecycle State  ──➔ **{inferred_lifecycle}**")
                print(f"   ➔ Parsed Structural Goal    ──➔ \"{p['active_subgoal']}\"")
                print(f"   ➔ Subgoal Context Container ──➔ \"{p['contained_plan']}\"")
                
                # Emit the highest-level hierarchical containment predicates directly to disk!
                t6_facts.append(f"life_goal(john, leadership_modality, partial_analogy_david).")
                t6_facts.append(f"current_season(john, activation_season_three).")
                t6_facts.append(f"plan_contained_in(amtrak_train_routing, business_meeting_startup, john_life_goal).")
            else:
                t6_facts.append(f"historical_exemplar({subj}, completed_leadership_arc).")

        # Commit compiled sovereign predicates straight into the planning workspace files
        t6_exs_path = os.path.join(self.root_dir, "grigorchuk_planning_space/exs.pl")
        with open(t6_exs_path, "w", encoding="utf-8") as f:
            f.write("%% Autogenerated Sovereign Top-Level Life-Goal Predicates\n")
            for fact in t6_facts:
                f.write(f"{fact}\n")

        print("-" * 95)
        print(f"💾 [WORLD FS UPDATE]: Master Sovereign predicates safely frozen to 'grigorchuk_planning_space/exs.pl'")
        print("=" * 95 + "\n")

if __name__ == "__main__":
    pipeline = SovereignInferencePipeline()
    pipeline.run_sovereign_inference()