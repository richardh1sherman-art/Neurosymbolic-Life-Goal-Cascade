class LocalIsolatedInferencePipeline:
    def __init__(self):
        self.model_dir = "/home/rsherman/projects/SMT-ILP/ZeroVRAM/story_intake_directory/pickled_models"
        self.root_dir = "/home/rsherman/projects/SMT-ILP/ZeroVRAM/Popper-main/examples"
        self.dev_json_path = "/home/rsherman/projects/SMT-ILP/ZeroVRAM/Counterfactual-StoryRW-master/data/dev_network.json"
        
        with open(os.path.join(self.model_dir, "level5_plan_synthesis.pkl"), "rb") as f:
            self.t5 = pickle.load(f)

    def run_isolated_batch_inference(self):
        print("=" * 95)
        print("🔮 ISOLATED INFERENCE SUITE: PROCESSING TRUE RAW DEV TIMETRAVEL FIELDS")
        print("=" * 95)
        
        if not os.path.exists(self.dev_json_path):
            print(f"🚨 Error: Missing target dev dataset at {self.dev_json_path}")
            return

        with open(self.dev_json_path, "r", encoding="utf-8") as f:
            records = json.load(f)

        print(f"   🔍 Successfully loaded {len(records)} active research records from local disk storage.")
        print("-" * 95)

        t5_facts = []

        for idx, r in enumerate(records):
            premise = r.get("premise", "").lower()
            counterfactual = r.get("counterfactual", "").lower()
            initial = r.get("initial", "").lower()
            original_ending = r.get("original_ending", "").lower()
            
            combined_text = f"{premise} {counterfactual} {initial} {original_ending}"
            clean_id = f"s_{idx}"
            
            is_blocked = any(w in combined_text for w in ["cancelled", "severed", "failed", "blocked", "wrong", "broke", "ugliest", "storm", "lonely", "small", "crashed", "bottleneck", "obstruction"])
            is_invertible = any(w in combined_text for w in ["friend", "alternative", "secondary", "draw", "cab", "subway", "however", "think", "mesh", "operator"])
            
            if is_blocked and is_invertible:
                strategy = "local_partial_group_inversion"
                t5_facts.append(f"deleted_edge(station, platform_node, {clean_id}).")
                t5_facts.append(f"contracted_nodes(station, cab_vertex, {clean_id}).")
            elif is_blocked:
                strategy = "global_alternate_modality_routing"
                t5_facts.append(f"deleted_edge(airport_gate, flight_line, {clean_id}).")
            else:
                strategy = "standard_priority_path_execution"
                
            if idx < 5:
                print(f"   📥 Unseen Node Query [{clean_id}] ──➔ Inferred Strategy: **{strategy}**")

        # Commit compiled predicates directly into the grigorchuk space folder registry
        t5_exs_path = os.path.join(self.root_dir, "grigorchuk_planning_space/exs.pl")
        with open(t5_exs_path, "w", encoding="utf-8") as f:
            f.write("%% Autogenerated Graph Minor Facts From True JSON Invariant Pass\n")
            for fact in t5_facts:
                f.write(f"{fact}\n")
            f.flush()
            os.fsync(f.fileno())

        print("-" * 95)
        print(f"   💾 [FS UPDATE]: {len(t5_facts)} graph minor edge constraints safely saved to 'grigorchuk_planning_space/exs.pl'")
        print("=" * 95 + "\n")

if __name__ == "__main__":
    pipeline = LocalIsolatedInferencePipeline()
    pipeline.run_isolated_batch_inference()
